@dataclass
class Constraint:
    expr: sp.Expr      # g for g <= 0, or h for h = 0
    eq: bool
    latex: str         # as typed, e.g. "x + y \ge 1"
    name: str          # "g₁" or "h₁"
    mname: str         # mathtext name, "g_1"
    affine: bool
    color: str
    fn: Callable = None
    grad: Callable = None
    hess: Callable = None


@dataclass
class Candidate:
    p: np.ndarray
    f: float                  # f(p) as typed
    phi: float                # objective in minimization form: f, or -f when maximizing
    grad_phi: np.ndarray
    active: list              # indices of the active constraints
    A: np.ndarray             # k x 2, gradients of the active constraints
    is_eq: np.ndarray         # which rows of A are equalities
    u: np.ndarray             # multipliers of the active constraints
    stationary: bool          # grad phi + A^T u = 0 for some u, ignoring signs
    kkt: bool                 # ... with u >= 0 on the inequalities
    unique: bool              # the multipliers are unique
    licq: bool
    mfcq: bool
    mfcq_d: Optional[np.ndarray]  # a direction showing MFCQ holds
    linear: bool
    acq: bool
    acq_implied: bool         # ACQ follows from LICQ, MFCQ or linear CQ
    T: np.ndarray             # tangent cone, as a mask over THETA
    L: np.ndarray             # linearized cone, as a mask over THETA
    cone: tuple               # cone generated by the active gradients
    crit: str = ""            # description of the critical cone C
    q_min: Optional[float] = None
    second: str = "n/a"       # pass, zero (C = {0}), fail, inconclusive or n/a
    hess_text: str = ""
    local: str = "unknown"    # min, not, flat, isolated or unknown
    local_how: str = ""
    glob: bool = False

    @property
    def dual_fail(self):
        return self.stationary and not self.kkt


