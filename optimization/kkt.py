def _rank(M):
    if M.size == 0:
        return 0
    sv = np.linalg.svd(M, compute_uv=False)
    return int(np.sum(sv > RANK_TOL * max(1.0, sv.max())))


def _parse_constraints(text):
    pieces = [piece.strip() for piece in text.split(";") if piece.strip()]
    if not pieces:
        raise ValueError("Enter at least one constraint, e.g. x + y >= 1")
    cons, n_ineq, n_eq = [], 0, 0
    for i, piece in enumerate(pieces, 1):
        piece_ = piece.replace("≤", "<=").replace("≥", ">=")
        op = next((o for o in ("<=", ">=", "==") if o in piece_), None)
        if op is None and any(o in piece_ for o in ("<", ">")):
            raise ValueError(f"Constraint {i} ({piece}) is strict: use <= or >= "
                             "(the feasible set must be closed)")
        if op is None:
            op = "=" if "=" in piece_ else None
        if op is None:
            raise ValueError(f"Constraint {i} ({piece}) needs <=, >= or =")
        sides = piece_.split(op)
        if len(sides) != 2 or any(s.count("=") or s.count("<") or s.count(">") for s in sides):
            raise ValueError(f"Constraint {i} ({piece}) should have exactly one <=, >= or =")
        lhs = parse_expr(sides[0], f"constraint {i}")
        rhs = parse_expr(sides[1], f"constraint {i}")
        eq = op in ("=", "==")
        expr = rhs - lhs if op == ">=" else lhs - rhs
        if not expr.free_symbols or sp.simplify(expr) == 0:
            value = sp.simplify(expr)
            ok = value == 0 if eq else bool(value <= 0)
            raise ValueError(f"Constraint {i} ({piece}) is {'always' if ok else 'never'} "
                             "satisfied")
        if eq:
            n_eq += 1
            name, mname = f"h{n_eq}".translate(SUB), f"h_{n_eq}"
        else:
            n_ineq += 1
            name, mname = f"g{n_ineq}".translate(SUB), f"g_{n_ineq}"
        rel = {"<=": r"\leq", ">=": r"\geq", "=": "=", "==": "="}[op]
        affine = bool(expr.is_polynomial(X, Y) and sp.Poly(expr, X, Y).total_degree() <= 1)
        cons.append(Constraint(expr, eq, f"{sp.latex(lhs)} {rel} {sp.latex(rhs)}", name, mname,
                               affine, CONSTRAINT_COLORS[(i - 1) % len(CONSTRAINT_COLORS)]))
    for c in cons:
        c.fn = vectorize(sp.lambdify(XY, c.expr, "numpy"))
        c.grad = sp.lambdify(XY, [sp.diff(c.expr, s) for s in XY], "numpy")
        c.hess = sp.lambdify(XY, sp.hessian(c.expr, XY).tolist(), "numpy")
    return cons


def _violation(cons, x, y):
    """max_i g_i(x, y) over the inequalities (-inf if there are none); NaN counts as +inf."""
    x, y = np.broadcast_arrays(np.asarray(x, float), np.asarray(y, float))
    G = np.full(x.shape, -np.inf)
    for c in cons:
        if not c.eq:
            G = np.maximum(G, np.nan_to_num(c.fn(x, y), nan=np.inf))
    return G


def _feasible_on_circle(cons, c, r, n=CIRCLE_ANGLES):
    """Feasible points on the circle of radius r around c, as an N x 2 array.

    With equality constraints these are isolated crossings. Otherwise the circle is
    sampled densely, and thin slivers between samples (like the region under
    (1 - x)^3 near x = 1) are found by minimizing the violation near its local minima.
    """
    eqs = [k.fn for k in cons if k.eq]
    if eqs:
        pts = circle_crossings(eqs, c, r, n)
        return pts[_violation(cons, pts[:, 0], pts[:, 1]) <= FEAS_TOL]
    t = np.linspace(0, 2 * np.pi, n, endpoint=False)
    G = _violation(cons, c[0] + r * np.cos(t), c[1] + r * np.sin(t))
    ok = G <= FEAS_TOL
    on_circle = lambda a: _violation(cons, c[0] + r * np.cos(a), c[1] + r * np.sin(a))
    step = t[1] - t[0]
    extra = []
    prev, nxt = np.roll(G, 1), np.roll(G, -1)
    minima = ~ok & np.isfinite(G) & (G <= prev) & (G <= nxt) & ((G < prev) | (G < nxt))
    idx = np.nonzero(minima)[0]
    for k in idx[np.argsort(G[idx])][:MAX_SLIVERS]:
        res = minimize_scalar(lambda a: float(on_circle(a)), bounds=(t[k] - step, t[k] + step),
                              method="bounded", options={"xatol": 1e-14})
        if res.fun <= FEAS_TOL:
            extra.append(res.x)
    a = np.concatenate([t[ok], extra])
    return np.stack([c[0] + r * np.cos(a), c[1] + r * np.sin(a)], axis=1)


def _mask_from_points(p, pts):
    """Directions from p to the points, rasterized onto THETA with a little slack."""
    mask = np.zeros(ANGLES, bool)
    if len(pts):
        ang = np.arctan2(pts[:, 1] - p[1], pts[:, 0] - p[0])
        mask[np.round(ang / (2 * np.pi) * ANGLES).astype(int) % ANGLES] = True
    return _dilate(mask, 1)


def _dilate(mask, cells):
    out = mask.copy()
    for s in range(1, cells + 1):
        out |= np.roll(mask, s) | np.roll(mask, -s)
    return out


def _halfplanes_mask(rows):
    """Directions u with a.u <= 0 for every nonzero row a."""
    mask = np.ones(ANGLES, bool)
    for a in rows:
        n = np.linalg.norm(a)
        if n > 0:
            mask &= a @ DIRS <= CELL_EPS * n
    return mask


def _lines_mask(rows):
    """Directions u with a.u = 0 for every nonzero row a."""
    mask = np.ones(ANGLES, bool)
    for a in rows:
        n = np.linalg.norm(a)
        if n > 0:
            mask &= np.abs(a @ DIRS) <= CELL_EPS * n
    return mask


def _runs(mask):
    """Contiguous runs of True in a circular mask, as (start, length) in cells."""
    if mask.all():
        return [(0, ANGLES)]
    if not mask.any():
        return []
    shift = int(np.argmin(mask))  # start scanning at a False cell
    m = np.roll(mask, -shift)
    runs, k = [], 0
    while k < ANGLES:
        if m[k]:
            j = k
            while j < ANGLES and m[j]:
                j += 1
            runs.append(((k + shift) % ANGLES, j - k))
            k = j
        else:
            k += 1
    return runs


def _generated_cone(vectors, lines):
    """Cone {sum mu_i v_i + sum lambda_j w_j : mu >= 0} in the plane.

    Returns (kind, start angle, extent) with kind zero, ray, line, sector or plane.
    """
    gens = [np.arctan2(v[1], v[0]) for v in vectors if np.linalg.norm(v) > 0]
    for w in lines:
        if np.linalg.norm(w) > 0:
            a = np.arctan2(w[1], w[0])
            gens += [a, a + np.pi]
    if not gens:
        return ("zero", 0.0, 0.0)
    gens = np.sort(np.mod(gens, 2 * np.pi))
    keep = np.concatenate([[True], np.diff(gens) > 1e-9])
    gens = gens[keep]
    if len(gens) > 1 and gens[-1] - gens[0] > 2 * np.pi - 1e-9:
        gens = gens[:-1]
    if len(gens) == 1:
        return ("ray", gens[0], 0.0)
    gaps = np.diff(np.concatenate([gens, [gens[0] + 2 * np.pi]]))
    i = int(np.argmax(gaps))
    start = gens[(i + 1) % len(gens)]
    extent = 2 * np.pi - gaps[i]
    if extent < np.pi - 1e-9:
        return ("sector", start, extent)
    if abs(extent - np.pi) <= 1e-9:
        inside = len(gens) > 2  # a generator strictly between the two ends
        return ("sector", start, extent) if inside else ("line", start, 0.0)
    return ("plane", 0.0, 2 * np.pi)


def _in_cone(cone, v):
    kind, start, extent = cone
    if np.linalg.norm(v) == 0:
        return True
    if kind == "plane":
        return True
    if kind == "zero":
        return False
    a = np.mod(np.arctan2(v[1], v[0]) - start, 2 * np.pi)
    tol = 1e-7
    if kind == "line":
        return min(a, abs(a - np.pi), 2 * np.pi - a) <= tol
    return a <= extent + tol or a >= 2 * np.pi - tol


def _convexity(expr, window):
    """(convex, numeric): exact for constant Hessians, else sampled over the window."""
    H = sp.hessian(expr, XY)
    if not H.free_symbols:
        return bool(np.linalg.eigvalsh(np.array(H, dtype=float)).min() >= -1e-12), False
    cx, cy, hw = window
    fn = sp.lambdify(XY, H.tolist(), "numpy")
    g = np.linspace(-hw, hw, 25)
    for x in cx + g:
        for y in cy + g:
            M = at(fn, (x, y))
            if not np.all(np.isfinite(M)) or np.linalg.eigvalsh(M).min() < -1e-9 * (1 + np.abs(M).max()):
                return False, True
    return True, True


def _candidates(phi_expr, cons, window, notes):
    """Points that may be KKT points or minimizers, from every active set.

    With k constraints treated as equalities: k = 0 solves grad phi = 0; k = 1 solves
    c = 0 and det[grad phi, grad c] = 0 (which also catches grad c = 0); k >= 2 takes
    every common solution (corners). All equalities are always included.
    """
    eqs = [c for c in cons if c.eq]
    ineqs = [c for c in cons if not c.eq]
    pts, exact = [], True
    max_extra = max(0, 2 - len(eqs))
    for size in range(0, min(max_extra, len(ineqs)) + 1):
        for subset in combinations(ineqs, size):
            S = eqs + list(subset)
            if not S:
                system = [sp.diff(phi_expr, s) for s in XY]
            elif len(S) == 1:
                c = S[0].expr
                det = sp.diff(phi_expr, X) * sp.diff(c, Y) - sp.diff(phi_expr, Y) * sp.diff(c, X)
                if sp.simplify(det) == 0:
                    notes.append(f"f is constant along {S[0].name} = 0: those points are all "
                                 "critical (not shown)")
                    continue
                system = [c, det]
            else:
                system = [c.expr for c in S]
            found, ok, continuum = solve(system, window)
            exact &= ok
            pts += found
            if continuum and not S:
                notes.append("grad f = 0 along a whole curve (not shown)")
            elif continuum:
                notes.append("Part of the candidates form a curve (not shown)")
    if not exact:
        notes.append("SymPy could not solve exactly: points were found numerically near "
                     "the window")
    pts = dedup(pts, window[2])
    feasible = []
    for p in pts:
        vals = [float(c.fn(*p)) for c in cons]
        if all(abs(v) <= 1e-8 if c.eq else v <= 1e-8 for v, c in zip(vals, cons)):
            feasible.append(p)
    return feasible, exact


def _local_numeric(cons, phi, p, phi0, hw):
    """Compare phi(p) with phi at nearby feasible points: min, not, flat or isolated."""
    for r in np.array(LOCAL_RADII) * hw:
        near = _feasible_on_circle(cons, p, r, 1440)
        if len(near):
            break
    else:
        return "isolated"
    diffs = phi(near[:, 0], near[:, 1]) - phi0
    tol = 1e-12 * (1 + abs(phi0))
    if np.any(diffs < -tol):
        return "not"
    return "min" if np.any(diffs > tol) else "flat"


def _analyze(p, f, phi, d_phi, h_phi, cons, hw):
    grad_phi = at(d_phi, p)
    active = [i for i, c in enumerate(cons)
              if c.eq or abs(float(c.fn(*p))) <= ACTIVE_TOL * (1 + np.abs(p).max())]
    A = np.array([at(cons[i].grad, p) for i in active], dtype=float).reshape(-1, 2)
    is_eq = np.array([cons[i].eq for i in active], bool)
    k, b = len(active), -grad_phi
    rank = _rank(A)
    licq = rank == k

    # Multipliers: least squares when unique, else an LP for some u with u_ineq >= 0.
    u = np.linalg.lstsq(A.T, b, rcond=None)[0] if k else np.zeros(0)
    stationary = np.linalg.norm(A.T @ u - b if k else b) <= 1e-7 * max(1.0, np.linalg.norm(b))
    kkt = False
    if stationary:
        if licq:
            tol = MU_TOL * (1 + np.abs(u).max(initial=0))
            kkt = bool(np.all(u[~is_eq] >= -tol))
            if kkt:
                u = np.where(~is_eq & (u < 0), 0.0, u)
        else:
            res = linprog(np.zeros(k), A_eq=A.T, b_eq=b, method="highs",
                          bounds=[(None, None) if e else (0, None) for e in is_eq])
            if res.status == 0:
                kkt, u = True, res.x

    # MFCQ: independent grad h and some d with grad h.d = 0 and grad g.d < 0 (active g).
    E, I = A[is_eq], A[~is_eq]
    mfcq, mfcq_d = False, None
    if _rank(E) == len(E):
        if len(I) == 0:
            mfcq = True
        else:
            res = linprog([0, 0, -1], A_ub=np.hstack([I, np.ones((len(I), 1))]),
                          b_ub=np.zeros(len(I)),
                          A_eq=np.hstack([E, np.zeros((len(E), 1))]) if len(E) else None,
                          b_eq=np.zeros(len(E)) if len(E) else None,
                          bounds=[(-1, 1), (-1, 1), (None, 1)], method="highs")
            if res.status == 0 and -res.fun > 1e-9:
                mfcq, mfcq_d = True, res.x[:2] / np.linalg.norm(res.x[:2])
    linear = all(cons[i].affine for i in active)

    # Cones: the linearized cone is exact; the tangent cone is estimated from feasible
    # points on a small circle around p.
    L = _halfplanes_mask(I) & _lines_mask(E)
    T = _mask_from_points(p, _feasible_on_circle(cons, p, TANGENT_RADIUS * hw))
    acq_implied = licq or mfcq or linear
    acq = acq_implied or bool(np.all(~L | _dilate(T, CONE_DILATE))
                              and np.all(~T | _dilate(L, CONE_DILATE)))

    cp = Candidate(p, float(f(*p)), float(phi(*p)), grad_phi, active, A, is_eq, u,
                   bool(stationary), kkt, licq, licq, mfcq, mfcq_d, linear, acq, acq_implied,
                   T, L, _generated_cone(I, E))
    if kkt:
        _second_order(cp, h_phi, cons)

    # Local verdict, in minimization form.
    if kkt and cp.second == "pass":
        cp.local, cp.local_how = "min", "the second-order sufficient condition holds"
    elif kkt and cp.second == "zero":
        cp.local, cp.local_how = "min", "C = {0}, so the first-order conditions alone suffice"
    elif kkt and cp.second == "fail" and licq:
        cp.local, cp.local_how = "not", "q < 0 on the critical cone (second-order necessary " \
                                        "condition fails)"
    elif cp.dual_fail and (licq or mfcq):
        cp.local, cp.local_how = "not", "a CQ holds but no μ ≥ 0 exists, so KKT fails"
    else:
        cp.local = _local_numeric(cons, phi, p, cp.phi, hw)
        why = ("second-order test inconclusive" if kkt else
               "KKT fails and no CQ holds" if not (licq or mfcq) else "KKT fails")
        cp.local_how = f"checked numerically on nearby feasible points ({why})"
    return cp


def _second_order(cp, h_phi, cons):
    """Critical cone, min of q = d^T (Hessian of L) d over it, and the Hessian tests."""
    H = at(h_phi, cp.p).reshape(2, 2)
    for ui, i in zip(cp.u, cp.active):
        H = H + ui * at(cons[i].hess, cp.p).reshape(2, 2)
    strong = cp.is_eq | (cp.u > MU_TOL * (1 + np.abs(cp.u).max(initial=0)))
    lines = [a for a in cp.A[strong] if np.linalg.norm(a) > 0]
    halves = [a for a in cp.A[~strong] if np.linalg.norm(a) > 0]
    r = _rank(np.array(lines).reshape(-1, 2))
    if r >= 2:
        dirs, cp.crit = [], "C = {0}: the strongly active gradients span the plane"
    elif r == 1:
        t = np.array([-lines[0][1], lines[0][0]]) / np.linalg.norm(lines[0])
        dirs = [d for d in (t, -t) if all(a @ d <= CELL_EPS * np.linalg.norm(a) for a in halves)]
        cp.crit = {2: f"C = the line through d = {vec(t)}", 1: f"C = the ray d = {vec(dirs[0])}"
                   if dirs else "", 0: "C = {0}"}[len(dirs)]
    else:
        mask = _halfplanes_mask(halves)
        dirs = list(DIRS[:, mask].T)
        runs = _runs(mask)
        if mask.all():
            cp.crit = "C = ℝ² (every direction)"
        elif not runs:
            cp.crit = "C = {0}"
        else:
            s, n = runs[0]
            cp.crit = (f"C = the sector from d = {vec(DIRS[:, s])} to "
                       f"{vec(DIRS[:, (s + n - 1) % ANGLES])}")
    weak = bool(np.any(~strong))
    if not dirs:
        cp.second = "zero"
    else:
        D = np.array(dirs)
        q = np.einsum("ki,ij,kj->k", D, H, D)
        cp.q_min = float(q.min())
        tol = SOSC_TOL * (1 + np.linalg.norm(H))
        cp.second = "pass" if cp.q_min > tol else "fail" if cp.q_min < -tol else "inconclusive"

    k = len(cp.active)
    if weak:
        names = ", ".join(cons[i].name for i, s in zip(cp.active, strong) if not s)
        cp.hess_text = (f"Bordered Hessian: not applicable: {names} weakly active (μ = 0), "
                        "so C is a cone rather than a subspace")
    elif not cp.licq:
        cp.hess_text = "Bordered Hessian: not applicable because LICQ fails"
    elif k == 0:
        d1, d2 = H[0, 0], np.linalg.det(H)
        kind = ("positive definite ⇒ strict local min" if d1 > 0 and d2 > 0 else
                "negative definite" if d1 < 0 and d2 > 0 else
                "indefinite ⇒ saddle point" if d2 < 0 else "semidefinite ⇒ inconclusive")
        cp.hess_text = (rf"No active constraints: Hessian $D_1$ = {fmt(d1)}, $D_2$ = {fmt(d2)} "
                        f"⇒ {kind}")
    elif k == 1:
        a = cp.A[0]
        B = np.block([[np.zeros((1, 1)), a[None, :]], [a[:, None], H]])
        det = np.linalg.det(B)
        t = np.array([-a[1], a[0]]) / np.linalg.norm(a)
        check = -float(a @ a) * float(t @ H @ t)
        sign = "< 0 ⇒ strict local min" if det < -1e-12 else "> 0 ⇒ not a min" if det > 1e-12 \
            else "= 0 ⇒ inconclusive"
        cp.hess_text = (rf"Bordered Hessian: $\det\bar H$ = {fmt(det)} {sign}   "
                        rf"(agrees: $-|\nabla c|^2 q$ = {fmt(check)})")
    else:
        cp.hess_text = r"Bordered Hessian: $\bar H$ is 4×4 and n − m = 0, so no minors to check"


def parse(f_text, g_text, w_text, sense="min"):
    """Parse user input, find and classify the candidate points. Raises ValueError."""
    expr = parse_expr(f_text, "f")
    cons = _parse_constraints(g_text)
    window = parse_window(w_text)
    cx, cy, hw = window
    phi_expr = expr if sense == "min" else -expr
    f = vectorize(sp.lambdify(XY, expr, "numpy"))
    phi = vectorize(sp.lambdify(XY, phi_expr, "numpy"))
    d_phi = sp.lambdify(XY, [sp.diff(phi_expr, s) for s in XY], "numpy")
    h_phi = sp.lambdify(XY, sp.hessian(phi_expr, XY).tolist(), "numpy")
    notes = []

    pts, exact = _candidates(phi_expr, cons, window, notes)
    points = []
    for p in pts:
        cp = _analyze(p, f, phi, d_phi, h_phi, cons, hw)
        # Keep KKT points, points that fail only the sign condition (to show why it
        # matters), and points where LICQ fails (a minimizer may hide there).
        if cp.kkt or cp.dual_fail or not cp.licq:
            points.append(cp)
    points.sort(key=lambda cp: cp.phi)

    # Convexity: f (or -f) convex, g_i convex, h_j affine.
    convex, convex_numeric = True, False
    for e in [phi_expr] + [c.expr for c in cons if not c.eq]:
        ok, numeric = _convexity(e, window)
        convex &= ok
        convex_numeric |= numeric
    convex &= all(c.affine for c in cons if c.eq)

    # Feasible region: closed unless a constraint is singular; bounded unless it reaches
    # a far-away circle. The same circles give samples of the objective on the region.
    closed = not any(singular(c.expr) for c in cons)
    radii = np.geomspace(1e-2 * hw, FAR_RADIUS * max(1.0, hw), FAR_CIRCLES)
    rings = [_feasible_on_circle(cons, (cx, cy), R) for R in radii]
    samples = np.vstack(rings)
    bounded = len(rings[-1]) == 0
    if not points and not len(samples):
        raise ValueError("The feasible region looks empty: no point satisfies every constraint")
    compact = closed and bounded

    # Global verdict (minimization form).
    has_global = False
    if points:
        phis = np.array([cp.phi for cp in points])
        tol = 1e-9 * (1 + np.abs(phis).max())
        kkt_phis = [cp.phi for cp in points if cp.kkt]
        if convex and kkt_phis:
            best, has_global = min(kkt_phis), True
        else:
            usable = [cp.phi for cp in points if cp.local != "not"]
            best = min(usable) if usable else np.inf
            if compact:
                has_global = bool(usable)
            else:
                sp_ = phi(samples[:, 0], samples[:, 1])
                sp_ = sp_[np.isfinite(sp_)]
                has_global = bool(usable) and not (sp_.size and sp_.min() < best - tol)
        if has_global:
            for cp in points:
                cp.glob = cp.phi <= best + tol and cp.local != "not"

    word = sense
    shape = ("closed" if closed else "maybe not closed (a constraint is singular)") + \
        (", bounded ⇒ compact" if compact else ", bounded" if bounded else ", unbounded")
    if convex:
        region_text = (f"Convex problem{' (checked numerically)' if convex_numeric else ''}: "
                       f"every KKT point is a global {word}.  Feasible region: {shape}")
    elif compact:
        region_text = f"Feasible region: {shape}, so a global {word} exists (EVT)"
    else:
        region_text = f"Feasible region: {shape}; not convex, so global {word}s were checked " \
                      "by sampling"

    # Slater (convex problems): a strictly feasible point with all g_i < 0.
    slater, slater_point = None, None
    if convex:
        g = np.linspace(-hw, hw, 121)
        Xs, Ys = np.meshgrid(cx + g, cy + g)
        Xs, Ys = Xs.ravel(), Ys.ravel()
        eq_cons = [c for c in cons if c.eq]
        if eq_cons:
            pts_eq = samples
            ok = np.ones(len(pts_eq), bool)
        else:
            pts_eq = np.stack([Xs, Ys], axis=1)
            ok = np.ones(len(pts_eq), bool)
        if len(pts_eq):
            ok &= _violation(cons, pts_eq[:, 0], pts_eq[:, 1]) < -1e-9
        slater = bool(ok.any())
        if slater:
            slater_point = pts_eq[np.argmax(ok)]
    return Problem(expr, sense, cons, window, f, phi, points, convex, convex_numeric,
                   region_text, slater, slater_point, has_global, notes)


def label(prob, cp):
    w = prob.word
    if cp.glob:
        return f"global {w}"
    if cp.local in ("min", "isolated", "flat"):
        return f"local {w}"
    if cp.dual_fail:
        return f"not a {w} (μ < 0)"
    return f"not a {w}" if cp.local == "not" else "unknown"


def _marker_style(prob, cp):
    """Shape: triangle for an extremum, x where KKT fails on the sign of mu, diamond
    where LICQ fails. Filled if global, hollow if local."""
    extremum = cp.glob or cp.local in ("min", "isolated", "flat")
    color = EXTREMUM_COLOR[prob.sense] if extremum else OTHER_COLOR
    if not cp.licq:
        marker = "D"
    elif extremum:
        marker = "v" if prob.sense == "min" else "^"
    else:
        marker = "X"
    return {"marker": marker, "mec": color, "mfc": color if cp.glob or marker == "X" else "white",
            "ls": "none"}


def title(prob, name=""):
    cons = ",   ".join(f"${c.latex}$" for c in prob.cons)
    text = rf"{prob.sense}imize  $f(x, y) = {sp.latex(prob.expr)}$     subject to     {cons}"
    return f"{name}\n{text}" if name else text


class View:
    """Contours of f with the feasible region (left) and a close-up of the point (right)."""

    def __init__(self, fig, prob):
        self.prob = prob
        self.ax = fig.add_axes([0.05, 0.22, 0.42, 0.68])
        self.axz = fig.add_axes([0.55, 0.22, 0.42, 0.68])
        self.axes = [self.ax, self.axz]
        self.dynamic = []

        cx, cy, hw = prob.window
        g = np.linspace(-hw, hw, GRID)
        self.X, self.Y = np.meshgrid(cx + g, cy + g)
        self.Z = prob.f(self.X, self.Y)
        shown = [cp.f for cp in prob.points
                 if abs(cp.p[0] - cx) <= hw and abs(cp.p[1] - cy) <= hw]
        self.lo, self.hi = value_limits(self.Z, shown)
        Zc = np.ma.masked_invalid(np.clip(self.Z, self.lo, self.hi))

        ax = self.ax
        levels = np.linspace(self.lo, self.hi, 16)
        self.fill = ax.contourf(self.X, self.Y, Zc, levels=levels, cmap="Greys")
        self.lines = ax.contour(self.X, self.Y, Zc, levels=levels, colors="gray", linewidths=0.5)
        self.region = self._shade_region(ax, self.X, self.Y)
        self.con_artists = self._draw_constraints(ax, self.X, self.Y, legend=True)
        for cp in prob.points:
            ax.plot(*cp.p, **_marker_style(prob, cp), ms=9, zorder=6)
        ax.set_xlim(cx - hw, cx + hw)
        ax.set_ylim(cy - hw, cy + hw)
        ax.set_aspect("equal")
        ax.set_xlabel("x")
        ax.set_ylabel("y")
        ax.set_title(r"Contours of $f$, feasible region in blue.  Orange: $f = k$", fontsize=9)

    def _shade_region(self, ax, X, Y):
        if all(c.eq for c in self.prob.cons):
            return None
        G = np.ma.masked_invalid(_violation(self.prob.cons, X, Y))
        if not (G <= 0).any():
            return None
        return ax.contourf(X, Y, G, levels=[float(G.min()) - 1, 0], colors=["tab:blue"])

    def _draw_constraints(self, ax, X, Y, legend=False):
        artists, handles = [], []
        for c in self.prob.cons:
            for seg in level_curves(c.fn, X, Y, c.fn(X, Y), 0.0):
                artists.append(ax.plot(seg[:, 0], seg[:, 1], color=c.color,
                                       lw=2.5 if c.eq else 1.8)[0])
            handles.append(Line2D([], [], color=c.color, lw=2,
                                  label=f"${c.mname}$:  ${c.latex}$"))
        if legend:
            ax.legend(handles=handles, loc="best", fontsize=8, framealpha=0.85)
        return artists

    def update(self, sel, k, alphas, show_cones):
        for artist in self.dynamic:
            artist.remove()
        self.dynamic.clear()
        ax, prob = self.ax, self.prob
        cx, cy, hw = prob.window
        for artist in (self.fill, self.lines):
            set_opacity(artist, alphas["f"])
        if self.region is not None:
            set_opacity(self.region, alphas["region"])
        for artist in self.con_artists:
            set_opacity(artist, alphas["constraint"])
        for seg in level_curves(prob.f, self.X, self.Y, self.Z, k):
            self.dynamic.append(ax.plot(seg[:, 0], seg[:, 1], color="tab:orange", lw=2)[0])

        self.axz.clear()
        if sel is None:
            self.axz.text(0.5, 0.5, "No candidate points", ha="center", va="center",
                          transform=self.axz.transAxes)
            self.axz.set_axis_off()
            return
        cp = prob.points[sel]
        z = ZOOM * hw
        self.dynamic.append(ax.plot(*cp.p, "o", ms=17, mfc="none", mec="black", mew=1.5,
                                    zorder=7)[0])
        box = Rectangle(cp.p - z, 2 * z, 2 * z, fill=False, ls="--", lw=1, color="black")
        ax.add_patch(box)
        self.dynamic.append(box)
        self._closeup(cp, z, alphas, show_cones)

    def _closeup(self, cp, z, alphas, show_cones):
        axz, prob, p = self.axz, self.prob, cp.p
        axz.set_axis_on()
        g = np.linspace(-z, z, ZOOM_GRID)
        X, Y = np.meshgrid(p[0] + g, p[1] + g)
        Z = prob.f(X, Y)
        if np.isfinite(Z).any():
            lo, hi = np.nanpercentile(Z, [1, 99])
            if hi > lo:
                set_opacity(axz.contour(X, Y, Z, levels=np.linspace(lo, hi, 12), colors="gray",
                                        linewidths=0.5), alphas["f"])
            for seg in level_curves(prob.f, X, Y, Z, cp.f):
                axz.plot(seg[:, 0], seg[:, 1], color="black", ls="--", lw=1)
        region = self._shade_region(axz, X, Y)
        if region is not None:
            set_opacity(region, alphas["region"])
        for artist in self._draw_constraints(axz, X, Y):
            set_opacity(artist, alphas["constraint"])

        # Cone generated by the active gradients, then the gradients and -grad phi.
        R = 0.8 * z
        kind, start, extent = cp.cone
        style = {"color": "tab:blue", "alpha": 0.18, "lw": 0}
        if kind == "plane":
            axz.add_patch(Circle(p, R, **style))
        elif kind == "sector":
            axz.add_patch(Wedge(p, R, np.degrees(start), np.degrees(start + extent), **style))
        elif kind in ("line", "ray"):
            ends = [start] if kind == "ray" else [start, start + np.pi]
            for a in ends:
                axz.plot([p[0], p[0] + R * np.cos(a)], [p[1], p[1] + R * np.sin(a)],
                         color="tab:blue", alpha=0.3, lw=8, solid_capstyle="butt")
        # Gradients longer than -grad f, so both show when they point the same way.
        arrow, arrow_f = 0.65 * z, 0.42 * z
        zero = []
        for i, a in zip(cp.active, cp.A):
            c = prob.cons[i]
            n = np.linalg.norm(a)
            if n == 0:
                zero.append(rf"$\nabla {c.mname} = 0$")
                continue
            for s in ((1, -1) if c.eq else (1,)):
                v = s * a / n * arrow
                axz.annotate("", p + v, p, arrowprops={"arrowstyle": "-|>", "color": c.color,
                                                       "lw": 2})
            axz.annotate(rf"$\nabla {c.mname}$", p + a / n * arrow, color=c.color, fontsize=11,
                         xytext=(5, 5), textcoords="offset points")
        g_neg = -cp.grad_phi
        n = np.linalg.norm(g_neg)
        name = r"$-\nabla f$" if prob.sense == "min" else r"$\nabla f$"
        if n > 0:
            color = "black" if _in_cone(cp.cone, g_neg) else "tab:red"
            axz.annotate("", p + g_neg / n * arrow_f, p,
                         arrowprops={"arrowstyle": "-|>", "color": color, "lw": 2.5})
            axz.annotate(name, p + g_neg / n * arrow_f, color=color, fontsize=12,
                         xytext=(5, -16), textcoords="offset points")
        else:
            zero.append(name + " = 0")
        if zero:
            axz.text(0.02, 0.02, ",  ".join(zero), transform=axz.transAxes, fontsize=10)

        handles = [Line2D([], [], color="tab:blue", alpha=0.3, lw=8,
                          label="cone of active gradients")]
        if show_cones:
            handles += self._draw_cones(cp, z)
        axz.legend(handles=handles, loc="upper left", fontsize=8, framealpha=0.85)
        axz.plot(*p, "o", color="black", ms=5, zorder=8)
        axz.set_xlim(p[0] - z, p[0] + z)
        axz.set_ylim(p[1] - z, p[1] + z)
        axz.set_aspect("equal")
        axz.set_xlabel("x")
        axz.set_ylabel("y")
        ok = "inside" if cp.kkt else "outside"
        axz.set_title(f"Close-up at p: {name} is {ok} the cone of active gradients", fontsize=9)

    def _draw_cones(self, cp, z):
        """Tangent cone (green) and linearized cone (dashed purple), as arcs and rays."""
        handles = []
        for mask, radius, style, text in (
                (cp.T, 0.5 * z, {"color": "tab:green", "lw": 4, "zorder": 6}, "tangent cone"),
                (cp.L, 0.56 * z, {"color": "tab:purple", "lw": 2, "ls": "--", "zorder": 7},
                 "linearized cone")):
            for s, n in _runs(mask):
                a = THETA[s] + np.arange(n) * 2 * np.pi / ANGLES
                if n <= 2 * CONE_DILATE + 3:  # a single direction
                    m = a[len(a) // 2]
                    self.axz.plot([cp.p[0], cp.p[0] + radius * np.cos(m)],
                                  [cp.p[1], cp.p[1] + radius * np.sin(m)], **style)
                    continue
                self.axz.plot(cp.p[0] + radius * np.cos(a), cp.p[1] + radius * np.sin(a), **style)
                if n < ANGLES:
                    for e in (a[0], a[-1]):
                        self.axz.plot([cp.p[0], cp.p[0] + radius * np.cos(e)],
                                      [cp.p[1], cp.p[1] + radius * np.sin(e)], **style)
            if not mask.any():
                self.axz.plot(*cp.p, "o", ms=12, mfc="none", mec=style["color"])
            handles.append(Line2D([], [], label=text + (" = {0}" if not mask.any() else ""),
                                  **style))
        return handles

    def remove(self):
        for ax in self.axes:
            ax.remove()


def _mark(ok):
    return "✓" if ok else "✗"


def _multipliers(prob, cp):
    parts = []
    for i, ui in zip(cp.active, cp.u):
        c = prob.cons[i]
        greek = "λ" if c.eq else "μ"
        parts.append(f"{greek}{c.name[1:]} = {fmt(ui)}")
    return ", ".join(parts)


def describe_tests(prob, sel):
    """Sections of the tests window: point, KKT, second order, verdict, color."""
    if sel is None:
        return "No candidate points found", "", "", "", "black"
    cp, w = prob.points[sel], prob.word
    act = ", ".join(rf"{prob.cons[i].name} ($\nabla {prob.cons[i].mname}$ = {vec(a)})"
                    for i, a in zip(cp.active, cp.A)) or "none (interior point)"
    point = (f"Point {sel + 1} of {len(prob.points)}:   p = {vec(cp.p)},   f(p) = {fmt(cp.f)}\n"
             f"Active constraints: {act}")

    grad = r"\nabla f" if prob.sense == "min" else r"-\nabla f"
    station = rf"Stationarity:  ${grad} + \sum\mu_i\nabla g_i + \sum\lambda_j\nabla h_j = 0$"
    if not cp.active:
        station += f"   {_mark(cp.stationary)}  (∇f = {vec(cp.grad_phi)})"
    elif cp.stationary:
        station += f"   ✓  with {_multipliers(prob, cp)}"
        if not cp.unique and cp.kkt:
            station += "  (not unique; one choice)"
    else:
        station += "   ✗  (no multipliers make it hold)"
    inactive = [c.name for i, c in enumerate(prob.cons) if i not in cp.active]
    primal = "Primal feasibility:  gᵢ(p) ≤ 0,  hⱼ(p) = 0   ✓" + \
        (f"  ({', '.join(inactive)} inactive)" if inactive else "")
    neg = [f"μ{prob.cons[i].name[1:]} = {fmt(ui)}" for i, ui, e in zip(cp.active, cp.u, cp.is_eq)
           if not e and ui < 0]
    if not cp.stationary:
        dual = "Dual feasibility:  μᵢ ≥ 0   —  (no multipliers to check)"
    else:
        dual = f"Dual feasibility:  μᵢ ≥ 0   {_mark(cp.kkt)}" + \
            (f"  ({', '.join(neg)} < 0)" if neg and not cp.kkt else "")
    slack = "Complementary slackness:  μᵢ gᵢ(p) = 0   ✓  (inactive constraints get μ = 0)"
    kkt = "\n".join([station, primal, dual, slack])

    if cp.kkt:
        q = "" if cp.q_min is None else rf",   min of $q = d^T\nabla^2 L\, d$ over C = {fmt(cp.q_min)}"
        verdict2 = {"pass": "q > 0 on C ⇒ strict local min (SOSC holds)",
                    "zero": "C = {0} ⇒ strict local min with no second-order condition needed",
                    "fail": "q < 0 for some d in C ⇒ not a local min",
                    "inconclusive": "q = 0 for some d in C ⇒ inconclusive"}[cp.second]
        second = f"Critical cone {cp.crit}{q}\n{verdict2}\n{cp.hess_text}"
    else:
        second = "Not a KKT point, so the second-order conditions do not apply"

    local = {"min": f"local {w}", "not": f"not a local {w}", "flat": f"non-strict local {w}",
             "isolated": f"strict local {w} (isolated feasible point)",
             "unknown": "unknown"}[cp.local]
    local = f"Local: {local}: {cp.local_how}" if cp.local != "isolated" else \
        f"Local: {local}"
    if cp.glob:
        why = ("convex problem and p is a KKT point" if prob.convex and cp.kkt else
               "smallest value among all candidates" + (", region compact (EVT)"
                                                       if "compact" in prob.region_text else
                                                       "; no sampled feasible point does better"))
        if prob.sense == "max":
            why = why.replace("smallest", "largest")
        glob = f"Global: global {w}: {why}"
    elif not prob.has_global:
        glob = f"Global: no global {w} exists (f improves without bound or the {w} is not attained)"
    else:
        best = min(c.phi for c in prob.points if c.glob)
        glob = f"Global: not a global {w}: f = {fmt(best if prob.sense == 'min' else -best)} " \
               "at another candidate"
    color = "tab:green" if cp.glob else "tab:orange" if cp.local in ("min", "isolated", "flat") \
        else "tab:red"
    return point, kkt, second, local + "\n" + glob, color


def summary(prob, sel):
    lines = [prob.region_text]
    if not prob.points:
        lines.append("No candidate points")
    start = 0 if sel is None else min(max(0, sel - LIST_ROWS // 2),
                                      max(0, len(prob.points) - LIST_ROWS))
    for i in range(start, min(start + LIST_ROWS, len(prob.points))):
        cp = prob.points[i]
        mark = "▸" if i == sel else "   "
        lines.append(f"{mark} {i + 1}. {vec(cp.p)}   f = {fmt(cp.f)}   KKT {_mark(cp.kkt)}   "
                     f"{label(prob, cp)}" + ("   ◇ LICQ fails" if not cp.licq else ""))
    if len(prob.points) > LIST_ROWS:
        lines.append(f"     ({len(prob.points)} points in all)")
    return "\n".join(lines + prob.notes)


def describe_cqs(prob, sel):
    """Sections of the CQ window: active constraints, CQs, hierarchy, meaning, color."""
    if sel is None:
        return "No candidate points found", "", "", "", "black"
    cp = prob.points[sel]
    if cp.active:
        rows = [f"{prob.cons[i].name}:  ${prob.cons[i].latex}$,   "
                rf"$\nabla {prob.cons[i].mname}(p)$ = {vec(a)}" for i, a in zip(cp.active, cp.A)]
        active = f"p = {vec(cp.p)}\n" + "\n".join(rows[:4])
    else:
        active = f"p = {vec(cp.p)} is an interior point: no constraint is active, so every CQ " \
                 "holds trivially"
    k = len(cp.active)
    licq = f"LICQ  {_mark(cp.licq)}   the active gradients are linearly " + \
        ("independent" if cp.licq else f"dependent (rank {_rank(cp.A)} < {k})")
    if cp.mfcq:
        mfcq = "MFCQ  ✓   " + (f"d = {vec(cp.mfcq_d)} points strictly into every active "
                                "inequality" + (" along the equalities" if cp.is_eq.any() else "")
                                if cp.mfcq_d is not None else "no active inequalities and "
                                "independent ∇h")
    else:
        mfcq = "MFCQ  ✗   " + ("the ∇hⱼ are dependent" if _rank(cp.A[cp.is_eq]) < cp.is_eq.sum()
                              else "no direction d has ∇gᵢ·d < 0 for every active gᵢ")
    acq = f"Abadie (ACQ)  {_mark(cp.acq)}   tangent cone " + ("=" if cp.acq else "≠") + \
        " linearized cone" + ("   (implied by LICQ, MFCQ or linear CQ)" if cp.acq_implied else
                              "   (compared numerically; see the close-up)")
    linear = f"Linear CQ  {_mark(cp.linear)}   the active constraints are " + \
        ("all affine" if cp.linear else "not all affine")
    if prob.slater is None:
        slater = "Slater  —   only defined for convex problems, and this one is not convex"
    elif prob.slater:
        slater = f"Slater  ✓   strictly feasible point {vec(prob.slater_point)} " \
                 "(all gᵢ < 0); a global property of the problem"
    else:
        slater = "Slater  ✗   no point has every gᵢ < 0 (checked by sampling)"
    cqs = "\n".join([licq, mfcq, acq, linear, slater])

    marks = lambda name, ok: f"{name} {_mark(ok)}"
    hierarchy = (f"{marks('LICQ', cp.licq)}  ⇒  {marks('MFCQ', cp.mfcq)}  ⇒  "
                 f"{marks('Abadie', cp.acq)}  ⇐  {marks('Linear CQ', cp.linear)}\n"
                 "Convex problem with Slater  ⇒  MFCQ at every feasible point\n"
                 "If any of these holds at a local min, the KKT conditions hold there")

    w = prob.word
    is_min = cp.local in ("min", "isolated", "flat")
    if cp.acq:
        meaning = f"A CQ holds at p, so if p is a local {w} it must be a KKT point.\n" + \
            ("p is a KKT point." if cp.kkt else f"p is not a KKT point, so it cannot be a "
                                                 f"local {w}.")
        color = "tab:green"
    elif is_min and not cp.kkt:
        meaning = (f"No CQ holds and p is a local {w} that is NOT a KKT point.\n"
                   "This is exactly why the KKT theorem needs a constraint qualification.")
        color = "tab:red"
    elif cp.kkt:
        meaning = ("No CQ holds here, yet the KKT conditions still hold:\n"
                   "CQs are sufficient for KKT at a minimizer, not necessary.")
        color = "tab:orange"
    else:
        meaning = (f"No CQ holds: a local {w} here would not have to satisfy KKT,\n"
                   f"but p is not a local {w} anyway.")
        color = "tab:orange"
    return active, cqs, hierarchy, meaning, color


class TestsWindow(SecondaryWindow):
    TITLE = "KKT conditions: tests"
    SIZE = (11, 8.5)
    SECTIONS = (("Selected point", 0.88), ("KKT conditions", 0.76),
                ("Second-order conditions", 0.585), ("Verdict", 0.44),
                ("Feasible region and all candidates", 0.31))
    VERDICT = 3

    def update(self, prob, sel, name):
        *texts, color = describe_tests(prob, sel)
        self.set_texts(title(prob, name), (*texts, summary(prob, sel)), color)


class CQWindow(SecondaryWindow):
    TITLE = "KKT conditions: constraint qualifications"
    SIZE = (11, 7.5)
    SECTIONS = (("Active constraints at p", 0.86), ("Constraint qualifications at p", 0.66),
                ("How they relate", 0.40), ("What this means here", 0.22))
    VERDICT = 3

    def update(self, prob, sel, name):
        *texts, color = describe_cqs(prob, sel)
        self.set_texts(title(prob, name), texts, color)


def build():
    """Create the visualizer window and return its figure (call plt.show() to run it)."""
    fig = plt.figure(figsize=(13, 8))
    fig.canvas.manager.set_window_title("KKT conditions")
    prob = parse(F_INIT, G_INIT, W_INIT, SENSE_INIT)
    state = {"prob": prob, "view": View(fig, prob), "sel": 0 if prob.points else None,
             "sense": SENSE_INIT, "example": 0, "name": EXAMPLES[0][0], "loading": False,
             "tests": None, "cqs": None}

    error = fig.text(0.1, 0.083, "", color="tab:red", fontsize=9)
    ax_f = fig.add_axes([0.08, 0.1, 0.3, 0.035])
    ax_g = fig.add_axes([0.5, 0.1, 0.28, 0.035])
    ax_w = fig.add_axes([0.87, 0.1, 0.08, 0.035])
    tb_f = TextBox(ax_f, "f = ", initial=F_INIT)
    tb_g = TextBox(ax_g, "constraints ", initial=G_INIT)
    tb_w = TextBox(ax_w, "window ", initial=W_INIT)
    buttons = {}
    for i, (key, text) in enumerate((("prev", "◀ prev"), ("next", "next ▶"),
                                     ("sense", f"mode: {SENSE_INIT}"), ("example", "examples ▸"),
                                     ("tests", "tests"), ("cqs", "CQs"))):
        buttons[key] = Button(fig.add_axes([0.47 + 0.0835 * i, 0.047, 0.077, 0.03]), text)
        buttons[key].label.set_fontsize(9)

    def small(slider):
        slider.label.set_fontsize(8)
        slider.valtext.set_fontsize(8)
        return slider

    alpha_sliders = {}
    for i, (key, text, color) in enumerate((("f", "f opacity", "gray"),
                                            ("region", "region opacity", "tab:blue"),
                                            ("constraint", "constraint opacity", "tab:purple"))):
        ax_alpha = fig.add_axes([0.14 + 0.33 * i, 0.018, 0.15, 0.016])
        alpha_sliders[key] = small(Slider(ax_alpha, text, 0.0, 1.0, valinit=ALPHAS[key],
                                          color=color))

    def make_k_slider():
        # The range of k follows the range of f in the window, so rebuild it.
        old = state.get("k")
        if old is not None:
            old.disconnect_events()
            old.ax.remove()
        view = state["view"]
        slider = small(Slider(fig.add_axes([0.08, 0.053, 0.3, 0.018]), "level k", view.lo,
                              view.hi, valinit=(view.lo + view.hi) / 2, color="tab:orange"))
        slider.on_changed(update)
        state["k"] = slider

    def update(_=None):
        prob, view, sel = state["prob"], state["view"], state["sel"]
        view.update(sel, state["k"].val, {k: s.val for k, s in alpha_sliders.items()},
                    show_cones=state["cqs"] is not None)
        for key in ("tests", "cqs"):
            if state[key] is not None:
                state[key].update(prob, sel, state["name"])
        fig.canvas.draw_idle()

    def submit(_=None, name=""):
        if state["loading"]:
            return
        try:
            prob = parse(tb_f.text, tb_g.text, tb_w.text, state["sense"])
        except ValueError as err:
            error.set_text(str(err))
            fig.canvas.draw_idle()
            return
        state["view"].remove()
        state.update(prob=prob, view=View(fig, prob), sel=0 if prob.points else None, name=name)
        make_k_slider()
        error.set_text("")
        fig.suptitle(title(prob, name), fontsize=11)
        update()

    def load_example(_=None):
        state["example"] = (state["example"] + 1) % len(EXAMPLES)
        name, f, g, w, sense = EXAMPLES[state["example"]]
        state["loading"] = True  # set all boxes, then parse once
        for box, text in ((tb_f, f), (tb_g, g), (tb_w, w)):
            box.set_val(text)
        state["loading"] = False
        state["sense"] = sense
        buttons["sense"].label.set_text(f"mode: {sense}")
        submit(name=f"Example {state['example'] + 1}: {name}")

    def toggle_sense(_=None):
        state["sense"] = "max" if state["sense"] == "min" else "min"
        buttons["sense"].label.set_text(f"mode: {state['sense']}")
        submit()

    def step(delta):
        n = len(state["prob"].points)
        if n:
            state["sel"] = (state["sel"] + delta) % n
            update()

    def show(key, cls):
        if state[key] is None:
            state[key] = cls(on_close=lambda: (state.update({key: None}), update()))
        else:
            state[key].raise_()
        update()

    def on_click(event):
        view, points = state["view"], state["prob"].points
        if event.inaxes is not view.ax or not points:
            return
        disp = view.ax.transData.transform(np.array([cp.p for cp in points]))
        dist = np.hypot(disp[:, 0] - event.x, disp[:, 1] - event.y)
        if dist.min() < 15:
            state["sel"] = int(dist.argmin())
            update()

    for box in (tb_f, tb_g, tb_w):
        box.on_submit(lambda _: submit())
    buttons["prev"].on_clicked(lambda _: step(-1))
    buttons["next"].on_clicked(lambda _: step(1))
    buttons["sense"].on_clicked(toggle_sense)
    buttons["example"].on_clicked(load_example)
    buttons["tests"].on_clicked(lambda _: show("tests", TestsWindow))
    buttons["cqs"].on_clicked(lambda _: show("cqs", CQWindow))
    fig.canvas.mpl_connect("button_press_event", on_click)
    for slider in alpha_sliders.values():
        slider.on_changed(update)
    make_k_slider()
    fig.suptitle(title(prob, f"Example 1: {EXAMPLES[0][0]}"), fontsize=11)
    state["name"] = f"Example 1: {EXAMPLES[0][0]}"
    update()
    # The canvas holds only weak references to widgets, so keep them alive with the figure.
    fig._keep = [tb_f, tb_g, tb_w, buttons, alpha_sliders, state]
    return fig


def main():
    build()
    plt.show()


if __name__ == "__main__":
    main()
