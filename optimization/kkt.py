"""Interactive visualizer for the Karush-Kuhn-Tucker (KKT) conditions.

Minimize (or maximize) f(x, y) subject to inequality constraints g_i(x, y) <= 0 and
equality constraints h_j(x, y) = 0. A point p satisfies the KKT conditions when

    stationarity              grad f + sum mu_i grad g_i + sum lambda_j grad h_j = 0
    primal feasibility        g_i(p) <= 0,  h_j(p) = 0
    dual feasibility          mu_i >= 0
    complementary slackness   mu_i g_i(p) = 0

Geometrically: -grad f lies in the cone generated by the gradients of the active
constraints (those with g_i(p) = 0, plus every h_j in both directions). At a local
min where a constraint qualification (CQ) holds, the KKT conditions must hold.

Type f and the constraints (separated by ;, each written with <=, >= or =) and press
Enter. The left panel shows contours of f, the feasible region and every candidate
point; the right panel is a close-up of the selected point showing the cone of
active gradients and -grad f. "tests" opens a window with the KKT conditions, the
second-order test on the critical cone and the global verdict; "CQs" opens one with
LICQ, MFCQ, Abadie, linear and Slater CQs (and draws the tangent and linearized
cones in the close-up). "examples" cycles through preset problems.
"""

